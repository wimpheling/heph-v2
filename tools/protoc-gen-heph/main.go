// Command protoc-gen-heph validates API documentation and generates an endpoint reference.
package main

import (
	"fmt"
	"github.com/wimpheling/heph-v2/internal/rpc/platform"
	"google.golang.org/protobuf/compiler/protogen"
	"strings"
)

func main() {
	protogen.Options{}.Run(func(plugin *protogen.Plugin) error {
		out := plugin.NewGeneratedFile("api/endpoints.md", "")
		out.P("# RPC endpoints")
		out.P()
		out.P("Generated from proto/. Run pnpm generate. Do not edit this file.")
		out.P()
		for _, file := range plugin.Files {
			if !file.Generate {
				continue
			}
			for _, message := range file.Messages {
				if err := fields(message); err != nil {
					return err
				}
			}
			for _, service := range file.Services {
				if strings.TrimSpace(string(service.Comments.Leading)) == "" {
					return fmt.Errorf("%s requires a service comment", service.Desc.FullName())
				}
				for _, method := range service.Methods {
					if strings.TrimSpace(string(method.Comments.Leading)) == "" {
						return fmt.Errorf("%s requires an endpoint comment", method.Desc.FullName())
					}
					auth, err := platform.Authentication(method.Desc)
					if err != nil {
						return err
					}
					out.P("## ", method.Desc.FullName())
					out.P()
					out.P("Authentication: `", auth.String(), "`.")
					out.P()
					out.P(strings.TrimSpace(string(method.Comments.Leading)))
					out.P()
					for _, message := range []*protogen.Message{method.Input, method.Output} {
						out.P("### ", message.Desc.Name())
						out.P()
						out.P("| Field | Type | Description |")
						out.P("| --- | --- | --- |")
						for _, field := range message.Fields {
							description := strings.ReplaceAll(strings.TrimSpace(string(field.Comments.Leading)), "\n", " ")
							description = strings.ReplaceAll(description, "|", "\\|")
							kind := field.Desc.Kind().String()
							if field.Message != nil {
								kind = string(field.Message.Desc.FullName())
							}
							if field.Enum != nil {
								kind = string(field.Enum.Desc.FullName())
							}
							if field.Desc.IsList() {
								kind = "repeated " + kind
							}
							out.P("| `", field.Desc.Name(), "` | `", kind, "` | ", description, " |")
						}
						out.P()
					}
				}
			}
		}
		return nil
	})
}
func fields(message *protogen.Message) error {
	if strings.TrimSpace(string(message.Comments.Leading)) == "" {
		return fmt.Errorf("%s requires a message comment", message.Desc.FullName())
	}
	for _, field := range message.Fields {
		if strings.TrimSpace(string(field.Comments.Leading)) == "" {
			return fmt.Errorf("%s requires a field comment", field.Desc.FullName())
		}
	}
	for _, nested := range message.Messages {
		if err := fields(nested); err != nil {
			return err
		}
	}
	return nil
}
